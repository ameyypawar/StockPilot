def add_field(run, instr, placeholder="1"):
    """Builds a Word complex field (begin/instrText/separate/<display text>/end)
    in `run`'s own <w:r>. The placeholder <w:t> is a SIBLING positioned after
    the "separate" fldChar, not nested inside it -- nesting it inside fldChar
    is invalid OOXML and neither Word nor python-docx will read it back as
    the run's text, which is what the placeholder is for."""
    r = run._r
    fld_begin = OxmlElement("w:fldChar")
    fld_begin.set(docx_qn("w:fldCharType"), "begin")
    instr_el = OxmlElement("w:instrText")
    instr_el.set(docx_qn("xml:space"), "preserve")
    instr_el.text = instr
    fld_sep = OxmlElement("w:fldChar")
    fld_sep.set(docx_qn("w:fldCharType"), "separate")
    placeholder_el = OxmlElement("w:t")
    placeholder_el.set(docx_qn("xml:space"), "preserve")
    placeholder_el.text = placeholder
    fld_end = OxmlElement("w:fldChar")
    fld_end.set(docx_qn("w:fldCharType"), "end")
    r.append(fld_begin)
    r.append(instr_el)
    r.append(fld_sep)
    r.append(placeholder_el)
    r.append(fld_end)


def add_page_field(paragraph):
    run = paragraph.add_run()
    run.font.size = DocxPt(9)
    run.font.color.rgb = SLATE_DOCX
    add_field(run, "PAGE", "1")


def add_toc(document, switches='TOC \\o "1-3" \\h \\z \\u',
            note_text="(Right-click here and choose \"Update Field\", or press F9, to build this table.)"):
    paragraph = document.add_paragraph()
    run = paragraph.add_run()
    add_field(run, switches, note_text)


FIG_SEQ_N = {"n": 0}
TABLE_SEQ_N = {"n": 0}


def add_seq_caption(document, label, text, counter, before=None):
    """Caption paragraph with a real Word SEQ field (label N: text) so the
    List of Figures / List of Tables (built from TOC \\c fields) populate
    correctly when the field is updated with F9."""
    counter["n"] += 1
    p = document.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_before = DocxPt(4)
    p.paragraph_format.space_after = DocxPt(14)
    r1 = p.add_run(f"{label} ")
    r1.font.bold = True
    r1.font.size = DocxPt(10)
    r1.font.color.rgb = TEAL_DOCX
    r2 = p.add_run()
    r2.font.bold = True
    r2.font.size = DocxPt(10)
    r2.font.color.rgb = TEAL_DOCX
    add_field(r2, f'SEQ {label} \\* ARABIC', str(counter["n"]))
    r3 = p.add_run(f": {text}")
    r3.font.size = DocxPt(10)
    r3.italic = True
    r3.font.color.rgb = SLATE_DOCX
    return p


def add_figure(document, image_path: Path, caption_text: str, width_cm=FIG_WIDTH_CM):
    if not image_path.exists():
        p = document.add_paragraph()
        r = p.add_run(f"[missing figure: {image_path.name}]")
        r.italic = True
        r.font.color.rgb = DocxColor(*hx(DANGER_HEX))
        return
    p = document.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run()
    run.add_picture(str(image_path), width=Cm(width_cm))
    add_seq_caption(document, "Figure", caption_text, FIG_SEQ_N)


def set_cell_shading(cell, hex_color):
    shd = OxmlElement("w:shd")
    shd.set(docx_qn("w:fill"), hex_color)
    cell._tc.get_or_add_tcPr().append(shd)


def add_docx_table(document, headers, rows, widths=None, caption=None, zebra=True):
    if caption:
        add_seq_caption(document, "Table", caption, TABLE_SEQ_N)
    table = document.add_table(rows=1, cols=len(headers))
    table.style = "Table Grid"
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    hdr_cells = table.rows[0].cells
    for i, h in enumerate(headers):
        hdr_cells[i].text = str(h)
        set_cell_shading(hdr_cells[i], DARK_HEX)
        for p in hdr_cells[i].paragraphs:
            p.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.LEFT
            for run in p.runs:
                run.font.bold = True
                run.font.color.rgb = DocxColor(0xFF, 0xFF, 0xFF)
                run.font.size = DocxPt(10)
    for ri, row in enumerate(rows):
        cells = table.add_row().cells
        for i, val in enumerate(row):
            cells[i].text = str(val)
            if zebra and ri % 2 == 1:
                set_cell_shading(cells[i], LIGHT_ROW_HEX)
            for p in cells[i].paragraphs:
                p.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.LEFT
                for run in p.runs:
                    run.font.size = DocxPt(10)
    if widths:
        for row in table.rows:
            for i, w in enumerate(widths):
                row.cells[i].width = w
    document.add_paragraph()
    return table


def add_code_block(document, code_text, caption=None):
    p = document.add_paragraph()
    p.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.LEFT
    p.paragraph_format.left_indent = DocxInches(0.15)
    p.paragraph_format.right_indent = DocxInches(0.15)
    p.paragraph_format.space_before = DocxPt(6)
    p.paragraph_format.space_after = DocxPt(4)
    p.paragraph_format.line_spacing = 1.05
    shd = OxmlElement("w:shd")
    shd.set(docx_qn("w:fill"), CODE_BG_HEX)
    p._p.get_or_add_pPr().append(shd)
    run = p.add_run(code_text)
    run.font.name = "Consolas"
    run.font.size = DocxPt(9)
    run.font.color.rgb = DocxColor(*hx(CODE_FG_HEX))
    if caption:
        cp = document.add_paragraph()
        cp.alignment = WD_ALIGN_PARAGRAPH.CENTER
        cr = cp.add_run(caption)
        cr.italic = True
        cr.font.size = DocxPt(9)
        cr.font.color.rgb = SLATE_DOCX
        cp.paragraph_format.space_after = DocxPt(12)
    else:
        document.add_paragraph()


